-- ProLink v2 — Base de dados de apoio a um Assistente Pessoal de Educação e Carreira
-- SGBD: MySQL 8.0.16+ (CHECK constraints efectivamente aplicadas desde MySQL 8.0.16)
-- ATENÇÃO: este script ELIMINA e recria todas as tabelas da base `prolink`.
-- Faça cópia se já existir informação importante. Execute em ambiente de desenvolvimento/teste.
-- TODOS os dados de currículos, custos, vagas, programas, percursos e oportunidades são DEMONSTRATIVOS.
-- Os nomes de instituições podem corresponder a entidades reais, mas as relações e ofertas NÃO estão validadas.
-- Não usar os registos de exemplo para candidaturas reais.

CREATE DATABASE IF NOT EXISTS prolink CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE prolink;
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS notificacao;
DROP TABLE IF EXISTS item_recomendacao;
DROP TABLE IF EXISTS sessao_recomendacao;
DROP TABLE IF EXISTS etapa_plano;
DROP TABLE IF EXISTS plano_pessoal;
DROP TABLE IF EXISTS candidatura_oportunidade;
DROP TABLE IF EXISTS candidatura_admissao;
DROP TABLE IF EXISTS oportunidade_guardada;
DROP TABLE IF EXISTS programa_guardado;
DROP TABLE IF EXISTS formacao_utilizador;
DROP TABLE IF EXISTS utilizador_area_interesse;
DROP TABLE IF EXISTS oportunidade_carreira;
DROP TABLE IF EXISTS oportunidade_programa;
DROP TABLE IF EXISTS oportunidade;
DROP TABLE IF EXISTS ciclo_admissao;
DROP TABLE IF EXISTS percurso_academico;
DROP TABLE IF EXISTS programa_carreira;
DROP TABLE IF EXISTS carreira_competencia;
DROP TABLE IF EXISTS competencia;
DROP TABLE IF EXISTS carreira_profissional;
DROP TABLE IF EXISTS disciplina_prerequisito;
DROP TABLE IF EXISTS item_plano_curricular;
DROP TABLE IF EXISTS plano_curricular;
DROP TABLE IF EXISTS disciplina;
DROP TABLE IF EXISTS programa_via_acesso;
DROP TABLE IF EXISTS oferta_programa;
DROP TABLE IF EXISTS programa_estudo;
DROP TABLE IF EXISTS utilizador;
DROP TABLE IF EXISTS via_ensino_secundario;
DROP TABLE IF EXISTS campus;
DROP TABLE IF EXISTS instituicao;
DROP TABLE IF EXISTS fonte_informacao;
DROP TABLE IF EXISTS area_formacao;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE area_formacao (
 id_area INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(100) NOT NULL UNIQUE,
 descricao VARCHAR(500) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB;

CREATE TABLE fonte_informacao (
 id_fonte INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(180) NOT NULL,
 tipo_fonte ENUM('INSTITUCIONAL','GOVERNAMENTAL','PORTAL_EDUCATIVO','EMPREGADOR','OUTRO') NOT NULL,
 url_base VARCHAR(500) NULL,
 nivel_confianca ENUM('OFICIAL','PARCEIRO','SECUNDARIO','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 data_ultima_verificacao DATE NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 observacoes VARCHAR(500) NULL
) ENGINE=InnoDB;

CREATE TABLE instituicao (
 id_instituicao INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(180) NOT NULL UNIQUE,
 tipo_entidade ENUM('UNIVERSIDADE','INSTITUTO_SUPERIOR','INSTITUTO_TECNICO','CENTRO_FORMACAO','EMPRESA','ORGANIZACAO') NOT NULL,
 provincia_sede VARCHAR(80) NOT NULL,
 cidade_sede VARCHAR(80) NOT NULL,
 site_oficial VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_verificacao ENUM('VERIFICADO','A_VERIFICAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_VERIFICAR',
 data_ultima_verificacao DATE NULL,
 CONSTRAINT fk_instituicao_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE campus (
 id_campus INT AUTO_INCREMENT PRIMARY KEY,
 id_instituicao INT NOT NULL,
 nome VARCHAR(160) NOT NULL,
 provincia VARCHAR(80) NOT NULL,
 cidade VARCHAR(80) NOT NULL,
 distrito VARCHAR(100) NULL,
 endereco VARCHAR(250) NULL,
 url_mapa VARCHAR(500) NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 CONSTRAINT uq_campus UNIQUE (id_instituicao,nome,cidade),
 CONSTRAINT fk_campus_instituicao FOREIGN KEY (id_instituicao) REFERENCES instituicao(id_instituicao) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_campus_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE via_ensino_secundario (
 id_via INT AUTO_INCREMENT PRIMARY KEY,
 sistema_curricular VARCHAR(120) NOT NULL,
 nome VARCHAR(140) NOT NULL,
 descricao VARCHAR(500) NOT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 id_fonte INT NULL,
 url_fonte VARCHAR(500) NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uq_via_sistema_nome UNIQUE (sistema_curricular,nome),
 CONSTRAINT fk_via_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE utilizador (
 id_utilizador INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NULL COMMENT 'Nunca armazenar palavra-passe em texto simples; hash calculado na aplicação',
 papel ENUM('ESTUDANTE','ORIENTADOR','ADMINISTRADOR') NOT NULL DEFAULT 'ESTUDANTE',
 data_nascimento DATE NULL,
 provincia VARCHAR(80) NOT NULL,
 nivel_atual ENUM('SECUNDARIO','TECNICO_MEDIO','LICENCIATURA','MESTRADO','DOUTORAMENTO','GRADUADO') NOT NULL,
 orcamento_mensal_mzn DECIMAL(10,2) NULL,
 aceita_mobilidade BOOLEAN NOT NULL DEFAULT FALSE,
 data_registo DATE NOT NULL,
 estado ENUM('ATIVO','INATIVO','BLOQUEADO') NOT NULL DEFAULT 'ATIVO',
 consentimento_dados BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT chk_utilizador_orcamento CHECK (orcamento_mensal_mzn IS NULL OR orcamento_mensal_mzn >= 0)
) ENGINE=InnoDB;

CREATE TABLE programa_estudo (
 id_programa INT AUTO_INCREMENT PRIMARY KEY,
 id_instituicao INT NOT NULL,
 id_area INT NOT NULL,
 nome VARCHAR(180) NOT NULL,
 nivel ENUM('TECNICO_MEDIO','CURSO_CURTO','CERTIFICACAO','LICENCIATURA','POS_GRADUACAO','MESTRADO','DOUTORAMENTO') NOT NULL,
 duracao_meses SMALLINT UNSIGNED NOT NULL,
 descricao TEXT NOT NULL,
 requisitos_gerais TEXT NOT NULL,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 data_ultima_verificacao DATE NULL,
 CONSTRAINT uq_programa_instituicao_nome UNIQUE (id_instituicao,nome),
 CONSTRAINT fk_programa_instituicao FOREIGN KEY (id_instituicao) REFERENCES instituicao(id_instituicao) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_programa_area FOREIGN KEY (id_area) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_programa_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_programa_duracao CHECK (duracao_meses > 0)
) ENGINE=InnoDB;

CREATE TABLE oferta_programa (
 id_oferta INT AUTO_INCREMENT PRIMARY KEY,
 id_programa INT NOT NULL,
 id_campus INT NOT NULL,
 modalidade ENUM('PRESENCIAL','HIBRIDO','ONLINE') NOT NULL,
 turno ENUM('DIURNO','POS_LABORAL','FIM_DE_SEMANA','FLEXIVEL','NAO_APLICAVEL') NOT NULL DEFAULT 'DIURNO',
 duracao_meses SMALLINT UNSIGNED NULL,
 custo_matricula_mzn DECIMAL(12,2) NULL,
 custo_mensal_mzn DECIMAL(12,2) NULL,
 moeda CHAR(3) NOT NULL DEFAULT 'MZN',
 activo BOOLEAN NOT NULL DEFAULT TRUE,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 data_ultima_verificacao DATE NULL,
 CONSTRAINT uq_oferta UNIQUE (id_programa,id_campus,modalidade,turno),
 CONSTRAINT fk_oferta_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_oferta_campus FOREIGN KEY (id_campus) REFERENCES campus(id_campus) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_oferta_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_oferta_duracao CHECK (duracao_meses IS NULL OR duracao_meses > 0),
 CONSTRAINT chk_oferta_matricula CHECK (custo_matricula_mzn IS NULL OR custo_matricula_mzn >= 0),
 CONSTRAINT chk_oferta_mensal CHECK (custo_mensal_mzn IS NULL OR custo_mensal_mzn >= 0)
) ENGINE=InnoDB;

CREATE TABLE programa_via_acesso (
 id_via INT NOT NULL,
 id_programa INT NOT NULL,
 condicoes_acesso TEXT NOT NULL,
 media_minima DECIMAL(4,1) NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 PRIMARY KEY (id_via,id_programa),
 CONSTRAINT fk_pva_via FOREIGN KEY (id_via) REFERENCES via_ensino_secundario(id_via) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_pva_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_pva_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_pva_media CHECK (media_minima IS NULL OR (media_minima BETWEEN 0 AND 20))
) ENGINE=InnoDB;

CREATE TABLE disciplina (
 id_disciplina INT AUTO_INCREMENT PRIMARY KEY,
 id_area INT NOT NULL,
 nome VARCHAR(140) NOT NULL UNIQUE,
 descricao VARCHAR(500) NOT NULL,
 carga_horaria_referencia SMALLINT UNSIGNED NOT NULL,
 CONSTRAINT fk_disciplina_area FOREIGN KEY (id_area) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_disciplina_horas CHECK (carga_horaria_referencia > 0)
) ENGINE=InnoDB;

CREATE TABLE plano_curricular (
 id_plano INT AUTO_INCREMENT PRIMARY KEY,
 id_programa INT NOT NULL,
 versao VARCHAR(40) NOT NULL,
 ano_referencia YEAR NOT NULL,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 UNIQUE KEY uq_plano_programa_versao (id_programa,versao),
 CONSTRAINT fk_plano_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_plano_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE item_plano_curricular (
 id_plano INT NOT NULL,
 numero_item SMALLINT UNSIGNED NOT NULL,
 id_disciplina INT NOT NULL,
 ano_curricular TINYINT UNSIGNED NOT NULL,
 semestre TINYINT UNSIGNED NOT NULL,
 creditos DECIMAL(4,1) NULL,
 carga_horaria SMALLINT UNSIGNED NOT NULL,
 obrigatoria BOOLEAN NOT NULL DEFAULT TRUE,
 PRIMARY KEY (id_plano,numero_item),
 CONSTRAINT fk_item_plano FOREIGN KEY (id_plano) REFERENCES plano_curricular(id_plano) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_item_disciplina FOREIGN KEY (id_disciplina) REFERENCES disciplina(id_disciplina) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_item_ano CHECK (ano_curricular BETWEEN 1 AND 8),
 CONSTRAINT chk_item_semestre CHECK (semestre BETWEEN 1 AND 2),
 CONSTRAINT chk_item_horas CHECK (carga_horaria > 0)
) ENGINE=InnoDB;

CREATE TABLE disciplina_prerequisito (
 id_disciplina INT NOT NULL,
 id_disciplina_requisito INT NOT NULL,
 tipo_requisito ENUM('PRE_REQUISITO','CO_REQUISITO') NOT NULL DEFAULT 'PRE_REQUISITO',
 observacao VARCHAR(300) NULL,
 PRIMARY KEY (id_disciplina,id_disciplina_requisito),
 CONSTRAINT fk_dp_disciplina FOREIGN KEY (id_disciplina) REFERENCES disciplina(id_disciplina) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_dp_requisito FOREIGN KEY (id_disciplina_requisito) REFERENCES disciplina(id_disciplina) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_disciplina_nao_propria CHECK (id_disciplina <> id_disciplina_requisito)
) ENGINE=InnoDB;

CREATE TABLE carreira_profissional (
 id_carreira INT AUTO_INCREMENT PRIMARY KEY,
 id_area INT NOT NULL,
 nome VARCHAR(140) NOT NULL UNIQUE,
 descricao TEXT NOT NULL,
 contexto_trabalho VARCHAR(500) NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 CONSTRAINT fk_carreira_area FOREIGN KEY (id_area) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE competencia (
 id_competencia INT AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(140) NOT NULL UNIQUE,
 descricao VARCHAR(500) NOT NULL,
 categoria ENUM('TECNICA','GESTAO','TRANSVERSAL') NOT NULL
) ENGINE=InnoDB;

CREATE TABLE carreira_competencia (
 id_carreira INT NOT NULL,
 id_competencia INT NOT NULL,
 nivel_importancia ENUM('BASICO','INTERMEDIO','AVANCADO') NOT NULL DEFAULT 'INTERMEDIO',
 PRIMARY KEY (id_carreira,id_competencia),
 CONSTRAINT fk_cc_carreira FOREIGN KEY (id_carreira) REFERENCES carreira_profissional(id_carreira) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_cc_competencia FOREIGN KEY (id_competencia) REFERENCES competencia(id_competencia) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE programa_carreira (
 id_programa INT NOT NULL,
 id_carreira INT NOT NULL,
 relacao VARCHAR(300) NOT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 PRIMARY KEY (id_programa,id_carreira),
 CONSTRAINT fk_pc_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_pc_carreira FOREIGN KEY (id_carreira) REFERENCES carreira_profissional(id_carreira) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE percurso_academico (
 id_percurso INT AUTO_INCREMENT PRIMARY KEY,
 id_area_origem INT NULL,
 id_programa_origem INT NULL,
 id_programa_destino INT NOT NULL,
 tipo_ligacao ENUM('AREA_PARA_CURSO','PROGRESSAO_ACADEMICA','ESPECIALIZACAO','ALTERNATIVA') NOT NULL,
 requisitos_resumo TEXT NOT NULL,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 CONSTRAINT fk_percurso_area FOREIGN KEY (id_area_origem) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_percurso_origem FOREIGN KEY (id_programa_origem) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_percurso_destino FOREIGN KEY (id_programa_destino) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_percurso_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_percurso_origem CHECK ((id_area_origem IS NOT NULL AND id_programa_origem IS NULL) OR (id_area_origem IS NULL AND id_programa_origem IS NOT NULL)),
 CONSTRAINT chk_percurso_distinto CHECK (id_programa_origem IS NULL OR id_programa_origem <> id_programa_destino)
) ENGINE=InnoDB;

CREATE TABLE ciclo_admissao (
 id_ciclo INT AUTO_INCREMENT PRIMARY KEY,
 id_oferta INT NOT NULL,
 ano_lectivo SMALLINT UNSIGNED NOT NULL,
 nome_ciclo VARCHAR(100) NOT NULL DEFAULT 'Admissão regular',
 vagas SMALLINT UNSIGNED NOT NULL,
 data_abertura DATE NULL,
 data_fecho DATE NULL,
 taxa_candidatura_mzn DECIMAL(10,2) NULL,
 requisitos_especificos TEXT NULL,
 estado ENUM('RASCUNHO','ABERTO','ENCERRADO','CANCELADO','A_VERIFICAR') NOT NULL DEFAULT 'A_VERIFICAR',
 url_candidatura VARCHAR(500) NULL,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'DEMONSTRACAO',
 data_ultima_verificacao DATE NULL,
 UNIQUE KEY uq_ciclo_oferta_ano_nome (id_oferta,ano_lectivo,nome_ciclo),
 CONSTRAINT fk_ciclo_oferta FOREIGN KEY (id_oferta) REFERENCES oferta_programa(id_oferta) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT fk_ciclo_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_ciclo_vagas CHECK (vagas > 0),
 CONSTRAINT chk_ciclo_taxa CHECK (taxa_candidatura_mzn IS NULL OR taxa_candidatura_mzn >= 0),
 CONSTRAINT chk_ciclo_datas CHECK (data_abertura IS NULL OR data_fecho IS NULL OR data_fecho >= data_abertura)
) ENGINE=InnoDB;

CREATE TABLE oportunidade (
 id_oportunidade INT AUTO_INCREMENT PRIMARY KEY,
 id_instituicao INT NULL,
 id_area INT NULL,
 titulo VARCHAR(180) NOT NULL,
 tipo ENUM('BOLSA','ESTAGIO','EMPREGO','CURSO_CURTO','INVESTIGACAO','VOLUNTARIADO') NOT NULL,
 descricao TEXT NOT NULL,
 localizacao VARCHAR(160) NOT NULL,
 data_publicacao DATE NULL,
 prazo_candidatura DATE NULL,
 estado_publicacao ENUM('ABERTA','ENCERRADA','CANCELADA','A_VERIFICAR') NOT NULL DEFAULT 'A_VERIFICAR',
 requisitos TEXT NULL,
 url_candidatura VARCHAR(500) NULL,
 url_fonte VARCHAR(500) NULL,
 id_fonte INT NULL,
 estado_dado ENUM('VERIFICADO','A_CONFIRMAR','DEMONSTRACAO') NOT NULL DEFAULT 'A_CONFIRMAR',
 data_ultima_verificacao DATE NULL,
 CONSTRAINT fk_oport_instituicao FOREIGN KEY (id_instituicao) REFERENCES instituicao(id_instituicao) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT fk_oport_area FOREIGN KEY (id_area) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT fk_oport_fonte FOREIGN KEY (id_fonte) REFERENCES fonte_informacao(id_fonte) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_oport_datas CHECK (prazo_candidatura IS NULL OR data_publicacao IS NULL OR prazo_candidatura >= data_publicacao)
) ENGINE=InnoDB;

CREATE TABLE oportunidade_programa (
 id_oportunidade INT NOT NULL,
 id_programa INT NOT NULL,
 observacao VARCHAR(300) NULL,
 PRIMARY KEY (id_oportunidade,id_programa),
 CONSTRAINT fk_op_programa_oportunidade FOREIGN KEY (id_oportunidade) REFERENCES oportunidade(id_oportunidade) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_op_programa_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE oportunidade_carreira (
 id_oportunidade INT NOT NULL,
 id_carreira INT NOT NULL,
 observacao VARCHAR(300) NULL,
 PRIMARY KEY (id_oportunidade,id_carreira),
 CONSTRAINT fk_oc_oportunidade FOREIGN KEY (id_oportunidade) REFERENCES oportunidade(id_oportunidade) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_oc_carreira FOREIGN KEY (id_carreira) REFERENCES carreira_profissional(id_carreira) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE utilizador_area_interesse (
 id_utilizador INT NOT NULL,
 id_area INT NOT NULL,
 prioridade TINYINT UNSIGNED NOT NULL DEFAULT 1,
 PRIMARY KEY (id_utilizador,id_area),
 CONSTRAINT fk_uai_utilizador FOREIGN KEY (id_utilizador) REFERENCES utilizador(id_utilizador) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_uai_area FOREIGN KEY (id_area) REFERENCES area_formacao(id_area) ON UPDATE CASCADE ON DELETE RESTRICT,
 CONSTRAINT chk_uai_prioridade CHECK (prioridade BETWEEN 1 AND 5)
) ENGINE=InnoDB;

CREATE TABLE formacao_utilizador (
 id_formacao INT AUTO_INCREMENT PRIMARY KEY,
 id_utilizador INT NOT NULL,
 id_programa INT NULL,
 id_instituicao INT NULL,
 nome_formacao VARCHAR(180) NOT NULL,
 nivel ENUM('ENSINO_SECUNDARIO','TECNICO_MEDIO','CURSO_CURTO','LICENCIATURA','POS_GRADUACAO','MESTRADO','DOUTORAMENTO','CERTIFICACAO','OUTRO') NOT NULL,
 ano_inicio SMALLINT UNSIGNED NULL,
 ano_fim SMALLINT UNSIGNED NULL,
 estado ENUM('EM_CURSO','CONCLUIDA','INTERROMPIDA','PLANEADA') NOT NULL DEFAULT 'EM_CURSO',
 instituicao_externa VARCHAR(180) NULL,
 observacoes VARCHAR(500) NULL,
 CONSTRAINT fk_fu_utilizador FOREIGN KEY (id_utilizador) REFERENCES utilizador(id_utilizador) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_fu_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT fk_fu_instituicao FOREIGN KEY (id_instituicao) REFERENCES instituicao(id_instituicao) ON UPDATE CASCADE ON DELETE SET NULL,
 CONSTRAINT chk_fu_anos CHECK (ano_inicio IS NULL OR ano_fim IS NULL OR ano_fim >= ano_inicio)
) ENGINE=InnoDB;

CREATE TABLE programa_guardado (
 id_utilizador INT NOT NULL,
 id_programa INT NOT NULL,
 data_guardado DATE NOT NULL,
 nota_pessoal VARCHAR(500) NULL,
 PRIMARY KEY (id_utilizador,id_programa),
 CONSTRAINT fk_pg_utilizador FOREIGN KEY (id_utilizador) REFERENCES utilizador(id_utilizador) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_pg_programa FOREIGN KEY (id_programa) REFERENCES programa_estudo(id_programa) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE oportunidade_guardada (
 id_utilizador INT NOT NULL,
 id_oportunidade INT NOT NULL,
 data_guardado DATE NOT NULL,
 PRIMARY KEY (id_utilizador,id_oportunidade),
 CONSTRAINT fk_og_utilizador FOREIGN KEY (id_utilizador) REFERENCES utilizador(id_utilizador) ON UPDATE CASCADE ON DELETE CASCADE,
 CONSTRAINT fk_og_oportunidade FOREIGN KEY (id_oportunidade) REFERENCES oportunidade(id_oportunidade) ON UPDATE CASCADE ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE candidatura_admissao (
 id_candidatura INT AUTO_INCREMENT PRIMARY KEY,
 id_utilizador INT NOT NULL,
 id_ciclo INT NOT NULL,
 estado ENUM('RASCUNHO','DOCUMENTOS_PENDENTES','SUBMETIDA','EM_AVALIACAO','ACEITE','REJEITADA','DESISTIU') NOT NULL DEFAULT 'RASCUNHO',
 data_criacao DATE NOT NULL,
 data_submissao DATE NULL,
 numero_protocolo VARCHAR(100) NULL,
